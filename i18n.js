function t(key, vars) {
  const pack = I18N[currentLang] || I18N.nl;
  let s = (pack && pack[key] != null) ? pack[key] : (I18N.nl[key] != null ? I18N.nl[key] : key);
  if (vars) Object.keys(vars).forEach(k => { s = String(s).split('{' + k + '}').join(vars[k]); });
  return s;
}

function detectLang() {
  try {
    const q = (new URLSearchParams(location.search).get('lang') || '').toLowerCase();
    if (LANGS.includes(q)) return q;
  } catch (e) {}
  try {
    const stored = localStorage.getItem('wijn-smaakquiz-lang');
    if (LANGS.includes(stored)) return stored;
  } catch (e) {}
  return 'nl';
}

function rewriteLangLinks() {
  document.querySelectorAll('a[href]').forEach(a => {
    const href = a.getAttribute('href');
    if (!href || href.startsWith('mailto:') || href.startsWith('http')) return;
    const m = href.match(/^(index\.html|stijl-[123]\.html)?(?:\?[^#]*)?(#.*)?$/);
    if (!m) return;
    const file = m[1] || '';
    const hash = m[2] || '';
    if (file) {
      a.setAttribute('href', file + '?lang=' + currentLang + hash);
    } else if ((hash || '') === '#prijzen' || href.indexOf('#prijzen') !== -1) {
      a.setAttribute('href', '?lang=' + currentLang + '#prijzen');
    }
  });
}

function applyTranslations() {
  document.documentElement.lang = currentLang;
  const titleKey = document.body && document.body.dataset.i18nTitle;
  if (titleKey) document.title = t(titleKey);
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const vars = el.dataset.i18nN ? { n: el.dataset.i18nN } : undefined;
    const text = t(el.dataset.i18n, vars);
    const field = el.querySelector('input, select, textarea');
    if (field) {
      const tn = [...el.childNodes].find(n => n.nodeType === 3 && n.textContent.trim());
      if (tn) tn.textContent = text;
      else el.insertBefore(document.createTextNode(text + ' '), field);
    } else {
      el.textContent = text;
    }
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  document.querySelectorAll('.langs [data-lang]').forEach(b => {
    b.setAttribute('aria-pressed', b.dataset.lang === currentLang ? 'true' : 'false');
    b.classList.toggle('on', b.dataset.lang === currentLang);
  });
  rewriteLangLinks();
}

function setLang(lang) {
  if (!LANGS.includes(lang)) lang = 'nl';
  currentLang = lang;
  try { localStorage.setItem('wijn-smaakquiz-lang', lang); } catch (e) {}
  try {
    const url = new URL(location.href);
    url.searchParams.set('lang', lang);
    history.replaceState(null, '', url.pathname + url.search + url.hash);
  } catch (e) {}
  applyTranslations();
  if (typeof window.onLangChange === 'function') window.onLangChange();
}

function bindLangSwitcher() {
  document.querySelectorAll('.langs').forEach(nav => {
    nav.addEventListener('click', e => {
      const b = e.target.closest('[data-lang]');
      if (!b) return;
      e.preventDefault();
      setLang(b.dataset.lang);
    });
  });
}

currentLang = detectLang();
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => { applyTranslations(); bindLangSwitcher(); });
} else {
  applyTranslations();
  bindLangSwitcher();
}
